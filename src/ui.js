export function avatarHTML(meta, sizeClass = "") {
  const name = meta?.name || "";
  if (meta?.img) {
    return `<div class="ava ${sizeClass}"><img src="${escape(meta.img)}" alt="${escape(name)}" onerror="this.parentNode.textContent='${escape(initials(name))}'"></div>`;
  }
  return `<div class="ava ${sizeClass}">${escape(initials(name))}</div>`;
}
