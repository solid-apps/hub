/**
 * ui.js — small shared UI helpers.
 *
 * Vanilla DOM. Apps render into a container element by setting innerHTML and
 * wiring event listeners. No framework — deliberate.
 */

export const $  = (sel, root = document) => root.querySelector(sel);
export const $$ = (sel, root = document) => Array.from(root.querySelectorAll(sel));

export function escape(s) {
  return String(s ?? "").replace(/[&<>"']/g, c => ({
    "&":"&amp;","<":"&lt;",">":"&gt;",'"':"&quot;","'":"&#39;",
  }[c]));
}

export function initials(name) {
  if (!name) return "?";
  return name.split(/\s+/).map(s => s[0]).filter(Boolean).slice(0, 2).join("").toUpperCase() || "?";
}

export function fmtBytes(b) {
  if (b == null) return "";
  if (b < 1024) return b + " B";
  if (b < 1024 * 1024) return (b / 1024).toFixed(1) + " KB";
  return (b / (1024 * 1024)).toFixed(2) + " MB";
}

export function fmtRel(iso) {
  const now = new Date();
  const d = new Date(iso);
  if (isNaN(d.getTime())) return "";
  const diff = (now - d) / 1000;
  if (diff < 60) return "just now";
  if (diff < 3600) return Math.floor(diff / 60) + "m ago";
  if (diff < 86400) return Math.floor(diff / 3600) + "h ago";
  const days = Math.floor(diff / 86400);
  if (days < 7) return days + "d ago";
  return d.toLocaleDateString("en-GB", { day: "numeric", month: "short" });
}

export function showToast(msg, kind) {
  const t = $("#toast");
  if (!t) return;
  t.textContent = msg;
  t.className = "toast show " + (kind || "");
  clearTimeout(showToast._t);
  showToast._t = setTimeout(() => t.classList.remove("show"), 2400);
}

/** Render an empty-state placeholder into a container. */
export function renderEmpty(container, opts = {}) {
  container.innerHTML = `
    <div class="empty">
      ${opts.icon || `<svg viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round"><circle cx="11" cy="11" r="8"/><path d="m21 21-4.3-4.3"/></svg>`}
      <div>${escape(opts.title || "Nothing here yet.")}</div>
      ${opts.body ? `<div style="margin-top:8px;font-size:13px">${escape(opts.body)}</div>` : ""}
    </div>
  `;
}

/**
 * Render the appropriate sign-in prompt for an app that requires a Solid pod.
 * - signed-out: prompt to log in
 * - signed in via Nostr: prompt to switch to the Solid tab
 *
 * Returns true if rendered (caller should return early), false otherwise.
 */
export function requireSolid(container, ctx, msg) {
  if (ctx.auth.type === "solid") return false;
  const isNostr = ctx.auth.type === "nostr";
  container.innerHTML = `<div class="content"><div class="page-pad">
    <div class="login-banner">
      <div class="ico">
        <svg viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="2" stroke-linecap="round" stroke-linejoin="round"><path d="M12 22s8-4 8-10V5l-8-3-8 3v7c0 6 8 10 8 10z"/></svg>
      </div>
      <div class="info">
        <strong>${isNostr ? "Signed in via Nostr — Solid required" : "Sign in to your Solid pod"}</strong>
        <span>${escape(msg || "hub-pod stores its data on a Solid pod. Click the floating Login button" + (isNostr ? ", log out, then sign in again on the Solid tab." : "; pick the Solid tab and choose your provider."))}</span>
      </div>
    </div>
  </div></div>`;
  return true;
}

export function renderSpinner(container) {
  container.innerHTML = `<div class="spinner"></div>`;
}

/** Debounce a function. */
export function debounce(fn, ms = 300) {
  let t;
  return function(...args) {
    clearTimeout(t);
    t = setTimeout(() => fn.apply(this, args), ms);
  };
}

